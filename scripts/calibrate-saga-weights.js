#!/usr/bin/env node
// Tunes the per-card drawing weights used by the Saga (sealed) deck generator so that, within a
// rarity, every card appears in generated decks at nearly the same rate. It simulates many decks
// through the REAL generator (src/shared/js/sealed-rules-private.js, tribe minimums included),
// nudges each card's weight toward its rarity's average appearance rate, repeats, then writes
// src/shared/js/saga-weights-private.js (card ids -> weights; no card names).
//
//   node scripts/calibrate-saga-weights.js "<path to the card set CSV export>" [--decks=6000] [--rounds=16]
//
// Re-run it whenever the card set or the generator rules change. The CSV itself is private
// data and must not be committed.
const fs = require('fs'), vm = require('vm'), path = require('path');
const root = path.join(__dirname, '..');
const csvPath = process.argv.slice(2).find(a=>!a.startsWith('--'));
const opt = (k, d)=>{ const a = process.argv.find(x=>x.startsWith('--'+k+'=')); return a ? +a.split('=')[1] : d; };
const DECKS = opt('decks', 6000), ROUNDS = opt('rounds', 16), FINAL = opt('final', 20000);
if(!csvPath){ console.error('usage: node scripts/calibrate-saga-weights.js "<cards.csv>"'); process.exit(1); }

const ctx = { console, Math }; vm.createContext(ctx);
vm.runInContext('var SAGA_CARD_WEIGHTS = {};', ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'src/shared/js/sealed-rules-private.js'), 'utf8') +
  '\nthis.buildSagaDeck=buildSagaDeck; this.rarityTier=rarityTier; this.isMainDeckEligibleType=isMainDeckEligibleType; this.sagaCardWeight=sagaCardWeight;', ctx);

function parseCSV(t){const rows=[];let r=[],f='',q=false;for(let i=0;i<t.length;i++){const c=t[i];if(q){if(c=='"'){if(t[i+1]=='"'){f+='"';i++}else q=false}else f+=c}else if(c=='"')q=true;else if(c==','){r.push(f);f=''}else if(c=='\n'){r.push(f);rows.push(r);r=[];f=''}else if(c!='\r')f+=c}if(f||r.length){r.push(f);rows.push(r)}return rows}
const rows = parseCSV(fs.readFileSync(csvPath, 'utf8'));
const hdr = rows[0];
let cards = rows.slice(1).filter(r=>r.length>1).map(r=>Object.fromEntries(hdr.map((h,i)=>[h, r[i]||''])));
cards = cards.filter(r=>{const t=(r.type||'').trim();if(!t||t.startsWith('Q - '))return false;if(t.startsWith('Z - '))return t==='Z - Custom'&&(r.name==='Resistance'||r.name==='Stronghold');return true});
cards.forEach(r=>{ r.type=r.type.trim(); r.aspect=r.aspect.trim(); r.loyalty=r.loyalty.trim(); });
const W = ctx.SAGA_CARD_WEIGHTS;
const tier = ctx.rarityTier;

// Appearance rate (share of decks containing the card) for every main-deck card of one side.
function measure(side, n){
  const seen = new Map();
  for(let i=0;i<n;i++){
    const d = ctx.buildSagaDeck(cards, side, ()=>true).deck;
    d.deckCards.forEach((k,id)=>seen.set(id,(seen.get(id)||0)+1));
  }
  const rates = new Map();
  cards.filter(c=>ctx.isMainDeckEligibleType(c, side)).forEach(c=>rates.set(c.id, (seen.get(c.id)||0)/n));
  return rates;
}
function byTier(rates){
  const m = {};
  rates.forEach((rate,id)=>{ const c = cards.find(x=>x.id===id); (m[tier(c)] ??= []).push({c, rate}); });
  return m;
}
const mean = a=>a.reduce((x,y)=>x+y,0)/a.length;
function report(side, rates){
  const out = {};
  Object.entries(byTier(rates)).forEach(([t,list])=>{
    const r = list.map(x=>x.rate), m = mean(r);
    out[t] = `${(100*m).toFixed(1)}% avg, ${(100*Math.min(...r)).toFixed(1)}–${(100*Math.max(...r)).toFixed(1)}%, spread ±${(100*Math.max(m-Math.min(...r), Math.max(...r)-m)/m).toFixed(0)}% (${list.length} cards)`;
  });
  console.log(side.padEnd(9), out);
}

for(const side of ['overlord','champion']){ console.log('BEFORE'); report(side, measure(side, FINAL)); }
for(let round=1; round<=ROUNDS; round++){
  for(const side of ['overlord','champion']){
    const rates = measure(side, DECKS);
    Object.values(byTier(rates)).forEach(list=>{
      const live = list.filter(x=>x.rate>0), target = mean(live.map(x=>x.rate));
      list.forEach(({c, rate})=>{
        const w = ctx.sagaCardWeight(c);
        const factor = // later rounds take smaller steps, so sampling noise doesn't jiggle the weights
           rate>0 ? Math.min(2, Math.max(0.5, Math.pow(target/rate, 0.6-0.3*round/ROUNDS))) : 1.5;
        W[c.id] = Math.min(12, Math.max(0.1, w*factor));
      });
    });
  }
  process.stdout.write(`round ${round}/${ROUNDS}\r`);
}
console.log('\nAFTER');
for(const side of ['overlord','champion']) report(side, measure(side, FINAL));

const body = Object.keys(W).sort().map(id=>`  ${JSON.stringify(id)}: ${+W[id].toFixed(3)},`).join('\n');
fs.writeFileSync(path.join(root, 'src/shared/js/saga-weights-private.js'),
`/* GENERATED by scripts/calibrate-saga-weights.js — do not edit by hand; re-run the script after the
   card set or the generator rules change. Per-card drawing weights (card id -> weight) for the Saga
   deck generator: tuned so cards of one rarity appear in generated decks at nearly the same rate. */
const SAGA_CARD_WEIGHTS = {
${body}
};
`);
console.log('wrote src/shared/js/saga-weights-private.js');
